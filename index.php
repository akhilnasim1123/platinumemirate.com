        lightGalleryFun()
        
        var numbersIncremented = false;
        
        document.addEventListener("scroll", function () {
            var targetDiv = document.getElementById("home-about-section");
            if (!targetDiv) return; 
        
            var targetDivRect = targetDiv.getBoundingClientRect();
            var targetDivTop = targetDivRect.top + window.scrollY;
            
            var scrollPosition = window.scrollY;
        
            var lowerThreshold = 600;
            if (checkScreenSize()) {
                lowerThreshold = 1200;
            }
            var upperThreshold = 2000;
        
            if (scrollPosition < lowerThreshold || scrollPosition > upperThreshold) {
                numbersIncremented = false;
            }
        
            if (scrollPosition >= lowerThreshold && scrollPosition <= upperThreshold && !numbersIncremented) {
          
                incEltNbr("year-count", 1, 200);     
                incEltNbr("countries-count", 1, 200);
                
                incEltNbr("client-count", 10, 50);      
                incEltNbr("project-count", 10, 50);     
                
                numbersIncremented = true;
            }
        });
        
        function incEltNbr(id, step, speed) {
            var elt = document.getElementById(id);
            if (elt) {
                var endNbr = Number(elt.innerHTML);
                incNbrRec(0, endNbr, elt, step, speed);
            } else {
                console.warn("Element with id '" + id + "' not found.");
            }
        }
        
        function incNbrRec(i, endNbr, elt, step, speed) {
            if (i <= endNbr) {
                elt.innerHTML = i;
                setTimeout(function () {
                    incNbrRec(i + step, endNbr, elt, step, speed);
                }, speed);
            } else {
                elt.innerHTML = endNbr;
            }
        }
        
    
        
